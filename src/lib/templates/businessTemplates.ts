// ビジネスタイプから適切なテンプレートを取得する関数
export function getBusinessTemplate(
  category: string,
  subCategory: string,
  businessType: string
): BusinessTemplate | null {
  const template = businessTemplates[category]?.[subCategory]?.[businessType]
  if (template) {
    return {
      ...template,
      category,
      subCategory,
      businessType
    }
  }
  return null
}

